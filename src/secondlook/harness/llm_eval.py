"""LLM Decision-Quality & Safety Monitoring Harness -- generic core.

Subsystem-agnostic: this module takes a `completion_fn` and a `score_fn`
and otherwise does not know what it is evaluating. Call-site knowledge
(how to invoke synthesis, how to wrap a trial-extraction `Report`) lives
only in `harness/adapters/`. Same discipline `signals/registry.py` applies
to its dispatch table.

A non-empty `safety_violations` list always produces
`verdict="BLOCKED_BY_SAFETY_VIOLATION"`, regardless of `pass_rate`. That
is the same precedence `validation.py`'s `HARD_REQUIRED_CONTROLS` applies
to the gold-standard pass rate.

Empty `cases`: `pass_rate` is 0.0 (not a `ZeroDivisionError`). An empty
set has never happened in practice; treating it as a perfect score would
be a fabricated accuracy claim.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Literal, Protocol

Verdict = Literal["PASS", "FAIL", "BLOCKED_BY_SAFETY_VIOLATION"]


@dataclass(frozen=True)
class EvalCase:
    input: dict
    expected: dict
    tolerance: dict | None = None


@dataclass(frozen=True)
class EvalResult:
    subsystem: str
    prompt_template_id: str
    pass_rate: float
    threshold: float
    safety_violations: list[str]
    verdict: Verdict


@dataclass(frozen=True)
class GroundingComparison:
    subsystem: str
    grounded: EvalResult
    ungrounded: EvalResult
    pass_rate_delta: float  # grounded.pass_rate - ungrounded.pass_rate


class CompletionFn(Protocol):
    def __call__(self, case_input: dict) -> dict: ...


class ScoreFn(Protocol):
    def __call__(
        self, expected: dict, actual: dict, tolerance: dict | None
    ) -> tuple[bool, list[str]]: ...


def derive_verdict(
    pass_rate: float,
    threshold: float,
    safety_violations: list[str],
) -> Verdict:
    """Safety violations always win, then the pre-committed threshold.

    Factored out of `run_eval_set` so adapters wrapping an already-scored
    object (the trial-extraction `Report`) reuse this precedence rather
    than reimplementing it.
    """
    if safety_violations:
        return "BLOCKED_BY_SAFETY_VIOLATION"
    if pass_rate >= threshold:
        return "PASS"
    return "FAIL"


def _unique_in_order(items: list[str]) -> list[str]:
    seen: set[str] = set()
    out: list[str] = []
    for item in items:
        if item not in seen:
            seen.add(item)
            out.append(item)
    return out


def render_markdown(
    results: list[EvalResult],
    *,
    comparisons: tuple[GroundingComparison, ...] = (),
    provenance: tuple[str, ...] = (),
) -> str:
    """Auditable report, same job `validation.py.render_markdown` does for gold-standard."""
    lines = [
        "# LLM Decision-Quality Eval Results",
        "",
        "Generated by `validation/llm_eval_run.py`. Thresholds were pre-committed",
        "in the adapters before any run and are not adjusted after seeing results.",
        "",
        "Safety-violation categories are intentionally narrow and will grow when",
        "issue #18 (guideline concordance) lands. Trial-criteria extraction and",
        "intake extraction have no ungrounded variant by design.",
        "",
    ]
    # A pass rate with no record of which backend produced it cannot be
    # audited or reproduced -- "100%" is a different claim depending on
    # whether a mock or a served model answered.
    if provenance:
        lines += ["## Run provenance", ""]
        lines += [f"- {line}" for line in provenance]
        lines += [""]
    for result in results:
        viol = ", ".join(result.safety_violations) if result.safety_violations else "none"
        lines += [
            f"## {result.subsystem} (`{result.prompt_template_id}`)",
            "",
            f"- **Pass rate:** {result.pass_rate:.0%} — threshold "
            f"{result.threshold:.0%} (pre-committed)",
            f"- **Safety violations:** {viol}",
            f"- **Verdict:** {result.verdict}",
            "",
        ]
    for comparison in comparisons:
        lines += [
            f"## Grounding comparison ({comparison.subsystem})",
            "",
            "Ungrounded means the underlying LLM answers with no tool/retrieval",
            "context, not an empty signals list.",
            "",
            f"- Grounded pass rate: {comparison.grounded.pass_rate:.0%} "
            f"({comparison.grounded.verdict})",
            f"- Ungrounded pass rate: {comparison.ungrounded.pass_rate:.0%} "
            f"({comparison.ungrounded.verdict})",
            f"- Delta (grounded − ungrounded): {comparison.pass_rate_delta:+.0%}",
            "",
        ]
        if comparison.pass_rate_delta <= 0:
            lines += [
                "> No positive lift from grounding on this eval set. That is a",
                "> signal the retrieval may not actually be used by the model.",
                "",
            ]
    return "\n".join(lines) + "\n"


def run_eval_set(
    cases: list[EvalCase],
    *,
    subsystem: str,
    prompt_template_id: str,
    completion_fn: CompletionFn,
    score_fn: ScoreFn,
    threshold: float,
) -> EvalResult:
    if not cases:
        violations: list[str] = []
        return EvalResult(
            subsystem=subsystem,
            prompt_template_id=prompt_template_id,
            pass_rate=0.0,
            threshold=threshold,
            safety_violations=violations,
            verdict=derive_verdict(0.0, threshold, violations),
        )

    passed_count = 0
    violations = []
    for case in cases:
        actual = completion_fn(case.input)
        passed, case_violations = score_fn(case.expected, actual, case.tolerance)
        if passed:
            passed_count += 1
        violations.extend(case_violations)

    unique = _unique_in_order(violations)
    pass_rate = passed_count / len(cases)
    return EvalResult(
        subsystem=subsystem,
        prompt_template_id=prompt_template_id,
        pass_rate=pass_rate,
        threshold=threshold,
        safety_violations=unique,
        verdict=derive_verdict(pass_rate, threshold, unique),
    )


def run_grounded_vs_ungrounded(
    cases: list[EvalCase],
    *,
    subsystem: str,
    prompt_template_id: str,
    grounded_completion_fn: CompletionFn,
    ungrounded_completion_fn: CompletionFn,
    score_fn: ScoreFn,
    threshold: float,
) -> GroundingComparison:
    grounded = run_eval_set(
        cases,
        subsystem=subsystem,
        prompt_template_id=prompt_template_id,
        completion_fn=grounded_completion_fn,
        score_fn=score_fn,
        threshold=threshold,
    )
    ungrounded = run_eval_set(
        cases,
        subsystem=subsystem,
        prompt_template_id=prompt_template_id,
        completion_fn=ungrounded_completion_fn,
        score_fn=score_fn,
        threshold=threshold,
    )
    return GroundingComparison(
        subsystem=subsystem,
        grounded=grounded,
        ungrounded=ungrounded,
        pass_rate_delta=grounded.pass_rate - ungrounded.pass_rate,
    )
